// quiz/progress.js — turns your study data into PROGRESS.md
//
//   npm run progress
//
// Reads plan/plan.json, vocab/day-XX.csv, journal/*.md, progress.json and
// history.json, then writes PROGRESS.md with a day-by-day table, quiz scores,
// a text learning curve and your hardest words. Commit PROGRESS.md daily.

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const read = (p, fallback) => {
  try {
    return JSON.parse(fs.readFileSync(path.join(ROOT, p), "utf8"));
  } catch {
    return fallback;
  }
};

const plan = read("plan/plan.json", { days: [] });
const progress = read("progress.json", {});
const history = read("history.json", []);
const journals = fs.existsSync(path.join(ROOT, "journal"))
  ? fs.readdirSync(path.join(ROOT, "journal")).filter((f) => /^\d{4}-\d{2}-\d{2}\.md$/.test(f))
  : [];

// words per day file
const wordsOf = (day) => {
  const f = path.join(ROOT, "vocab", `day-${String(day).padStart(2, "0")}.csv`);
  if (!fs.existsSync(f)) return [];
  return fs
    .readFileSync(f, "utf8")
    .split(/\r?\n/)
    .slice(1)
    .filter((l) => l.trim())
    .map((l) => l.split(",")[0].trim());
};

// a word counts as "learned" once you've answered it right more often than wrong, at least twice
const learned = (w) => {
  const p = progress[w];
  return p && p.right >= 2 && p.right > p.wrong;
};

// best score per "day N" quiz
const bestForDay = {};
for (const h of history) {
  const m = /^day (\d+)$/.exec(h.mode);
  if (m) bestForDay[m[1]] = Math.max(bestForDay[m[1]] ?? 0, h.percent);
}

let total = 0;
let totalLearned = 0;
const rows = [];
const curve = [];
for (const d of plan.days) {
  const words = wordsOf(d.day);
  const l = words.filter(learned).length;
  total += words.length;
  totalLearned += l;
  curve.push({ day: d.day, total, learned: totalLearned });
  const best = bestForDay[d.day];
  const status = words.length && l === words.length ? "✅" : l > 0 || best != null ? "🟡" : "⬜";
  rows.push(
    `| ${status} | ${d.day} | ${d.title} | ${d.pages} | ${l}/${words.length} | ${best != null ? best + "%" : "–"} |`
  );
}

// text learning curve: one bar per day, length = learned words so far
const max = Math.max(1, ...curve.map((c) => c.total));
const bar = (n) => "█".repeat(Math.round((n / max) * 40));
const curveText = curve
  .map((c) => `Day ${String(c.day).padStart(2)} │${bar(c.learned).padEnd(40)}│ ${c.learned}/${c.total}`)
  .join("\n");

const hardest = Object.entries(progress)
  .filter(([, p]) => p.wrong > p.right)
  .sort(([, a], [, b]) => b.wrong - b.right - (a.wrong - a.right))
  .slice(0, 10)
  .map(([w, p]) => `- **${w}** (✅ ${p.right} ❌ ${p.wrong})`);

const recent = history
  .slice(-10)
  .reverse()
  .map((h) => `| ${h.date} | ${h.mode}${h.reverse ? " (reverse)" : ""} | ${h.score}/${h.asked} | ${h.percent}% |`);

const md = `# 📈 Progress

_Generated by \`npm run progress\` on ${new Date().toISOString().slice(0, 10)}. Don't edit by hand._

| Words learned | Quiz sessions | Journal entries | Days done |
|---|---|---|---|
| **${totalLearned}** / ${total} | **${history.length}** | **${journals.length}** | **${rows.filter((r) => r.startsWith("| ✅")).length}** / ${plan.days.length} |

A word counts as learned when you've answered it right at least twice, and more often right than wrong.

## Learning curve

\`\`\`
${curveText}
\`\`\`

## Day by day

| | Day | Topic | Book pages | Learned | Best quiz |
|---|---|---|---|---|---|
${rows.join("\n")}

## Recent quizzes

| Date | Mode | Score | % |
|---|---|---|---|
${recent.join("\n") || "| – | – | – | – |"}

## Words to review

${hardest.join("\n") || "Nothing yet — keep quizzing!"}
`;

fs.writeFileSync(path.join(ROOT, "PROGRESS.md"), md);
console.log(curveText);
console.log(`\n${totalLearned}/${total} words learned · ${history.length} quizzes · ${journals.length} journal entries`);
console.log("Wrote PROGRESS.md");
